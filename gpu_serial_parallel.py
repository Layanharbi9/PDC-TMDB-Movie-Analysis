def trim_tail_only(s: str) -> str:
    return s.rstrip()


def clean_genre_c_style(s: str) -> str:
    if s is None:
        return ""
    temp_chars = []
    for ch in s:
        if ch not in ['"', '[', ']']:
            temp_chars.append(ch)
    tmp = "".join(temp_chars)
