def insert_top_py(arr, title, year, rev, pop, score, max_top=MAX_TOP):
    if score <= 0:
        return

    n = len(arr)

    if n < max_top:
        pos = n
        arr.append(None)
        while pos > 0 and score > arr[pos-1]["score"]:
            arr[pos] = arr[pos-1]
            pos -= 1
        arr[pos] = {
            "title": title,
            "year": year,
            "revenue": rev,
            "popularity": pop,
            "score": score,
        }
        return

    if score <= arr[-1]["score"]:
        return

    pos = max_top - 1
    while pos > 0 and score > arr[pos-1]["score"]:
        arr[pos] = arr[pos-1]
        pos -= 1

    arr[pos] = {
        "title": title,
        "year": year,
        "revenue": rev,
        "popularity": pop,
        "score": score,
    }


